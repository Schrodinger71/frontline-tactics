const News = (() => {
  const KEY = 'ft.news';
  const latest = () => (NEWS[0] || {}).v || '';
  const seen = () => { try { return localStorage.getItem(KEY) || '' } catch (e) { return latest() } };
  /** есть непрочитанное — показываем точку на кнопке меню */
  const unseen = () => !!latest() && seen() !== latest();
  const markSeen = () => { try { localStorage.setItem(KEY, latest()) } catch (e) { /* приватный режим */ } };

  function html(esc) {
    if (!NEWS.length) return '<p class="mu">Пока нечего рассказать.</p>';
    /* «текущая» — только если версия записи и правда совпадает с версией игры */
    const cur = typeof GAME_VERSION === 'string' ? GAME_VERSION : '';
    const li = it => `<li${it.n ? ' class="new"' : ''}><b>${esc(it.h)}</b>${it.n ? '<i class="tag">новое</i>' : ''}
      <span>${esc(it.d)}</span></li>`;
    const groupsOf = r => r.groups || [{ items: r.items || [] }];
    /** разделы выпуска; pick отбирает, какие пункты показывать */
    const body = (r, pick) => groupsOf(r).map(gr => {
      const items = (gr.items || []).filter(pick || (() => true));
      if (!items.length) return '';
      return `${gr.g ? `<div class="ngrp">${esc(gr.g)}</div>` : ''}<ul class="nlist">${items.map(li).join('')}</ul>`;
    }).join('');
    const head = r => `${esc(r.v)}${r.v === cur ? ' · текущая' : ''}${r.d ? ' · ' + esc(r.d) : ''}`;

    const countAll = r => groupsOf(r).reduce((a, gr) => a + (gr.items || []).length, 0);
    return NEWS.map((r, i) => {
      /* Текущий выпуск показан целиком, прошлые — под кнопкой «Развернуть». */
      if (i === 0) return `<div class="nrel"><div class="nver">${head(r)}</div>${r.t ? `<h2>${esc(r.t)}</h2>` : ''}${body(r)}</div>`;
      return `<details class="nrel old"><summary>
        <span class="nhd"><span class="nver">${head(r)}</span>${r.t ? `<b>${esc(r.t)}</b>` : ''}</span>
        <span class="nbtn"><span class="c">Развернуть · ${countAll(r)}</span><span class="o">Свернуть</span></span>
      </summary>${body(r)}</details>`;
    }).join('');
  }
  return { latest, unseen, markSeen, html };
})();
