/* ---------- текущий шаг ---------- */
const isLab = () => !!(G.scen && G.scen.tutorial && !G.spec && !G.over && G.roomId);
/** первый не сделанный и не пропущенный шаг текущего хода сцены */
function coachCur() {
  if (!isLab() || !G.isMyTurn) return null;
  if (!G.coachSkip) G.coachSkip = new Set();
  if (!G.coachDone) G.coachDone = new Set();
  const same = COACH.map((s, i) => i).filter(i => COACH[i].sc === G.scen.id && COACH[i].t === G.turn);
  for (const i of same) {
    if (G.coachSkip.has(i)) continue;
    /* сделанный шаг остаётся сделанным: режим или выбор сбрасываются сразу после действия */
    if (!G.coachDone.has(i)) { let d = false; try { d = COACH[i].done() } catch (e) { d = false } if (d) G.coachDone.add(i) }
    if (G.coachDone.has(i)) continue;
    return { i, s: COACH[i], n: same.indexOf(i) + 1, of: same.length };
  }
  return null;
}

let coachKey = -1, coachEl = null;
/** каждый кадр и после каждого обновления интерфейса: подсветка цели и карточка шага */
function coachTick() {
  const cur = coachCur();
  const wait = !cur && isLab() && !G.isMyTurn;
  const key = cur ? cur.i : wait ? -3 : -1;
  if (key !== coachKey) { coachKey = key; coachCard(cur, wait) }
  let el = null;
  G.coachHex = -1;
  if (cur) {
    let tg = null; try { tg = cur.s.target() } catch (e) { tg = null }
    if (tg && Number.isInteger(tg.hex) && tg.hex >= 0) G.coachHex = tg.hex;
    if (tg && tg.sel) el = document.querySelector(tg.sel);
    /* кнопка в свёрнутой боковой панели — раскрыть панель, иначе подсветку не видно */
    if (el && el.closest('#dock') && $('#dock').classList.contains('col')) setDock(true);
  }
  if (el !== coachEl) {
    if (coachEl) coachEl.classList.remove('coach-hl');
    coachEl = el;
    if (el) { el.classList.add('coach-hl'); if (el.closest('#rc') && el.scrollIntoView) el.scrollIntoView({ block: 'nearest' }) }
  }
}
/** карточка шага: сцена, шаг, текст, точки прогресса и кнопки */
function coachCard(cur, wait) {
  const el = $('#tutor');
  if (!el) return;
  const no = labIndex(G.scen && G.scen.id) + 1, name = G.scen ? G.scen.n : '';
  if (wait) {
    el.innerHTML = `<div class="tk">Сцена ${no} из ${LABS.length} · ${esc(name)}</div><div class="ctitle">Ход противника</div>
      <div class="ctext">Следующий шаг — когда снова будет ваш ход.</div>`;
    el.hidden = false;
    return;
  }
  if (!cur) { el.hidden = true; return }
  const dots = Array.from({ length: cur.of }, (_, j) => `<i class="${j < cur.n - 1 ? 'done' : j === cur.n - 1 ? 'now' : ''}"></i>`).join('');
  el.innerHTML = `<div class="tk">Сцена ${no} из ${LABS.length} · ${esc(name)} · шаг ${cur.n} из ${cur.of}</div>
    <div class="ctitle">${esc(cur.s.title)}</div>
    <div class="ctext">${cur.s.text}</div>
    <div class="cdots">${dots}</div>
    <p class="acts">${cur.s.info ? '<button class="btn sm pri" id="coachNext">Дальше</button>' : '<button class="btn sm" id="coachSkip">Пропустить шаг</button>'} <button class="btn sm" id="coachMenu">К списку сцен</button></p>`;
  el.hidden = false;
  const fwd = set => { set.add(cur.i); coachKey = -2; coachTick() };
  if (cur.s.info) $('#coachNext').onclick = () => fwd(G.coachDone); else $('#coachSkip').onclick = () => fwd(G.coachSkip);
  $('#coachMenu').onclick = () => { leaveToMenu(); M.view = 'learn'; showMenu() };
}
/** новая партия или выход: шаги и подсветка — с чистого листа */
function coachReset() {
  G.coachSkip = new Set(); G.coachDone = new Set(); G.coachHex = -1;
  coachKey = -1;
  if (coachEl) coachEl.classList.remove('coach-hl');
  coachEl = null;
  const el = $('#tutor'); if (el) el.hidden = true;
}
/** кольцо и указатель над клеткой, куда нажать (рисуется на карте поверх фишек) */
function drawCoachRing() {
  if (!(G.coachHex >= 0) || G.rp) return;
  const p = .5 + .5 * Math.sin(ANIM * 6), s = G.view.s, R = Hex.R * s;
  hexPath(G.coachHex, 1.08);
  cx.lineWidth = 5.4; cx.strokeStyle = 'rgba(0,0,0,.55)'; cx.stroke();
  cx.lineWidth = 3.2; cx.strokeStyle = `rgba(255,214,121,${.6 + .4 * p})`; cx.stroke();
  const q = w2s(H.center(G.coachHex)), y = q.y - R * 1.15 - p * 6;
  cx.beginPath(); cx.moveTo(q.x, y); cx.lineTo(q.x - 9, y - 13); cx.lineTo(q.x + 9, y - 13); cx.closePath();
  cx.fillStyle = '#ffd679'; cx.strokeStyle = 'rgba(0,0,0,.7)'; cx.lineWidth = 1.4; cx.fill(); cx.stroke();
}

