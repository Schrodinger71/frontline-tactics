/* ---------- выборки по видимому игроку состоянию ---------- */
/** клетка по колонке и ряду — как в расстановке сцены */
const hx = (c, r) => r * H.COLS + c;
/** своя часть типа k, n-я по порядку появления */
const own = (k, n) => G.units.filter(u => u.side === G.side && u.k === k).sort((a, b) => a.id - b.id)[n || 0] || null;
const foes = () => G.units.filter(e => e.side !== G.side && e.str > 0);
/** противник, по которому часть может ударить: соседний, у артиллерии — в её радиусе */
function foeFor(u) {
  const r = UT[u.k].bomb ? UT[u.k].bomb.rng : 1;
  return foes().filter(e => H.hexDist(u.hex, e.hex) <= r).sort((a, b) => H.hexDist(u.hex, a.hex) - H.hexDist(u.hex, b.hex))[0] || null;
}

/* ---------- шаги ---------- */
const COACH = [];
let SC = null;
const scene = id => { SC = id };
const step = (t, o) => COACH.push(Object.assign({ sc: SC, t }, o));
/** пояснение: ждёт кнопки «Дальше» */
const info = (t, title, text) => step(t, { title, text, info: true, target: () => null, done: () => false });
/** выбрать свою часть */
const sel = (t, k, n, title, text) => step(t, {
  title, text,
  target: () => { const u = own(k, n); return u ? { hex: u.hex } : null },
  done: () => { const u = own(k, n); return !u || G.sel === u.id }
});
/** перевести часть в клетку (c, r): пока часть не выбрана — кольцо на ней, потом на клетке */
const move = (t, k, n, c, r, title, text) => step(t, {
  title, text,
  target: () => { const u = own(k, n); return u ? { hex: G.sel === u.id ? hx(c, r) : u.hex } : null },
  done: () => { const u = own(k, n); return !u || u.hex === hx(c, r) }
});
/** нажать кнопку или клавишу; если для кнопки нужна выбранная часть (k, n) и она не выбрана — кольцо на ней */
const btn = (t, selq, done, title, text, k, n) => step(t, {
  title, text,
  target: () => { const u = k ? own(k, n) : null; return u && G.sel !== u.id ? { hex: u.hex } : { sel: selq } },
  done
});
/** ударить выбранной частью по противнику в досягаемости (атака, обстрел, разведка боем или огонь — по включённому режиму) */
const hit = (t, k, n, title, text) => step(t, {
  title, text,
  target: () => { const u = own(k, n); if (!u) return null; if (G.sel !== u.id) return { hex: u.hex }; const e = foeFor(u); return e ? { hex: e.hex } : null },
  /* после удачной атаки подвижная часть получает прорыв и снова «не действовала» — удар всё равно засчитан */
  done: () => { const u = own(k, n); return !u || !!u.acted || !!u.exploit }
});
const end = t => step(t, {
  title: 'Закончите ход',
  text: 'Нажмите кнопку «Конец хода» вверху экрана или клавишу <kbd>Enter</kbd>, чтобы передать ход противнику.',
  target: () => ({ sel: '#btnEnd' }), done: () => G.turn > t || !G.isMyTurn
});

