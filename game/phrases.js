const last = {};
let lastN = 0;
function phr(key, args, u) {
  const set = PH[key];
  if (!set) return '';
  let list = (set.all || []).slice();
  if (u && u.trait && set[u.trait]) list = list.concat(set[u.trait], set[u.trait]);
  if (!list.length) return '';
  const memo = key + (u ? u.id : '');
  let f;
  if (list.length < 2) f = list[0];
  else { do f = list[Math.floor(Math.random() * list.length)]; while (f === last[memo]); }
  last[memo] = f;
  if (++lastN > 20000) { for (const k in last) delete last[k]; lastN = 0 }
  return f(args || {});
}
